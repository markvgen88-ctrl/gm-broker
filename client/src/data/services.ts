/**
 * Каталог услуг. Один источник данных для: главной (блок «Услуги» и выбор
 * в первом экране), меню «Услуги» в шапке, подвала и страниц /services/:slug.
 * Чтобы добавить или переименовать услугу — правьте только этот файл.
 */
export type ServiceGroup = "person" | "business" | "extra" | "legal";

export interface ServiceSection {
  heading: string;
  paragraphs?: string[];
  list?: string[];
}

export interface CaseStudy {
  title: string;
  /** Исходные «стоп-факторы» клиента. */
  was: string[];
  /** Что было сделано. */
  done: { title: string; text: string }[];
  /** Ключевые цифры результата. */
  requested: string;
  approved: string;
  details: { label: string; value: string }[];
  quote?: string;
  /** Этапы сопровождения «под ключ». */
  steps: { title: string; text: string }[];
  /** Ситуации, с которыми работает брокер. */
  situations: string[];
  volume?: string;
  disclaimer: string;
}

export interface Service {
  slug: string;
  title: string;
  group: ServiceGroup;
  icon: IconType;
  /** Одна строка для карточек и меню. */
  short: string;
  /** Вступление на странице услуги (и meta description). */
  lead: string;
  forWhom: string[];
  whatIDo: string[];
  /** Третий список. Если пустой — колонка на странице не показывается. */
  prepare: string[];
  /** Подробное описание (для юридических услуг): блоки с заголовком, абзацами и списком. */
  sections?: ServiceSection[];
  /** Важная оговорка, показывается отдельной плашкой (необязательно). */
  note?: string;
  /** Свои заголовки трёх списков (по умолчанию: «Кому подходит», «Что я делаю», «Что понадобится»). */
  listTitles?: [string, string, string];
  /** Срок услуги — показывается плашкой под заголовком. */
  term?: string;
  /**
   * Вместо приглашения пройти опрос внизу страницы показывается форма заявки
   * именно на эту услугу: в письме и Telegram будет указано её название.
   */
  requestForm?: boolean;
  /** Подзаголовок над формой заявки (необязательно, есть общий текст). */
  requestText?: string;
  /** Текст после отправки формы (необязательно, есть общий текст). */
  requestSuccess?: string;
  /** Подсказка в поле «Комментарий» формы (необязательно). */
  requestPlaceholder?: string;
  /** Статья сайта по теме (необязательно). */
  article?: { slug: string; label: string };
  /** Разбор кейса — заметный блок на странице услуги (необязательно). */
  caseStudy?: CaseStudy;
}

